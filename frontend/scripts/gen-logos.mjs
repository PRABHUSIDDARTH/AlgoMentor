// Regenerates src/content/logos.ts: the Simple Icons (CC0) logo for every directory company that has one.
// Run: node scripts/gen-logos.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import * as si from 'simple-icons'

const src = readFileSync(new URL('../src/content/directory.ts', import.meta.url), 'utf8')
const rows = [...src.matchAll(/\['([a-z0-9-]+)', '([^']+)', '[A-Z]{2}'/g)].map((m) => ({ id: m[1], name: m[2] }))
const byTitle = new Map(Object.values(si).filter((i) => i && i.title).map((i) => [i.title.toLowerCase(), i]))
// Where the directory name differs from the Simple Icons title.
const ALIAS = {
  'samsung': 'Samsung', 'lg': 'LG', 'dell': 'Dell', 'tcs': 'Tata Consultancy Services',
  'booking': 'Booking.com', 'deepmind': 'DeepMind', 'walmart': 'Walmart', 'jio': 'Jio', 'ocado': 'Ocado', 'jd': 'JD.com',
  'x': 'X', 'snap': 'Snapchat', 'electronic-arts': 'EA', 'hcltech': 'HCL', 'epic-games': 'Epic Games', 'red-hat': 'Red Hat',
  'deutsche-telekom': 'Deutsche Telekom', 'goldman-sachs': 'Goldman Sachs', 'check-point': 'Check Point', 'monday': 'monday.com',
  'opentext': 'OpenText', 'sony': 'Sony', 'foxconn': 'Foxconn',
}
const out = {}
for (const r of rows) {
  const icon = byTitle.get((ALIAS[r.id] ?? r.name).toLowerCase())
  if (icon) out[r.id] = { title: icon.title, hex: icon.hex, path: icon.path }
}
const body = Object.entries(out).map(([id, v]) => `  ${JSON.stringify(id)}: ${JSON.stringify(v)},`).join('\n')
writeFileSync(new URL('../src/content/logos.ts', import.meta.url), `// Generated by scripts/gen-logos.mjs from simple-icons (CC0-1.0). Logos are trademarks of their owners. Do not edit.
export type Logo = { title: string; hex: string; path: string }

export const LOGOS: Record<string, Logo> = {
${body}
}
`)
console.log(`${Object.keys(out).length} of ${rows.length} companies have a logo`)
console.log('without:', rows.filter((r) => !out[r.id]).map((r) => r.name).join(', '))
