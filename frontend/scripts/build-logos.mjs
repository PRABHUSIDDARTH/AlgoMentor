// Merges public/logos/manifest.<batch>.json into public/logos/manifest.json and regenerates src/content/logos.ts.
// A logo is only listed if its file exists and its source is on the company's own site. Run: node scripts/build-logos.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = new URL('../public/logos/', import.meta.url).pathname
const dirSrc = readFileSync(new URL('../src/content/directory.ts', import.meta.url), 'utf8')
const ids = new Set([...dirSrc.matchAll(/\['([a-z0-9-]+)', '[^']+', '[A-Z]{2}'/g)].map((m) => m[1]))
const banned = /simpleicons|cdn\.jsdelivr|unpkg|iconify|wikimedia|wikipedia|logo\.dev|clearbit|brandfetch/i

const entries = new Map()
const rejected = []
for (const f of readdirSync(dir).filter((n) => /^manifest\.\d+\.json$/.test(n))) {
  const { entries: list = [], failed = [] } = JSON.parse(readFileSync(join(dir, f), 'utf8'))
  for (const e of list) {
    if (!ids.has(e.id)) rejected.push(`${e.id}: not in the directory`)
    else if (!existsSync(join(dir, e.file))) rejected.push(`${e.id}: file ${e.file} missing`)
    else if (!/^https:\/\//.test(e.source) || banned.test(e.source)) rejected.push(`${e.id}: source ${e.source}`)
    else entries.set(e.id, e)
  }
  for (const x of failed) rejected.push(`${x.id}: ${x.reason}`)
}
const sorted = [...entries.values()].sort((a, b) => a.id.localeCompare(b.id))
writeFileSync(join(dir, 'manifest.json'), JSON.stringify(sorted, null, 2) + '\n')
const body = sorted.map((e) => `  ${JSON.stringify(e.id)}: ${JSON.stringify({ file: e.file, source: e.source, page: e.page, kind: e.kind ?? 'unknown', ...(e.primary ? { primary: e.primary } : {}), ...(/white|light/i.test(e.note ?? '') ? { onDark: true } : {}), fetched: e.fetched })},`).join('\n')
writeFileSync(new URL('../src/content/logos.ts', import.meta.url), `// Generated by scripts/build-logos.mjs from public/logos/manifest.json. Do not edit.
export type OfficialLogo = { file: string; source: string; page: string; kind: 'wordmark' | 'symbol' | 'unknown'; primary?: string; onDark?: boolean; fetched: string }

/** Logos taken from each company's own website. A company missing here has no logo: AlgoMentor shows its name in plain type instead. */
export const OFFICIAL_LOGOS: Record<string, OfficialLogo> = {
${body}
}
`)
console.log(`${sorted.length} logos listed; ${rejected.length} not listed`)
for (const r of rejected) console.log('  -', r)
